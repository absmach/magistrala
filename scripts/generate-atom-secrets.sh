# Generate the Atom bootstrap YAML and .env.tokens file from a single set of
# operator-supplied service secrets. Replaces the imperative
# `atom-bootstrap provision-tokens` binary.
#
# For each Magistrala service that talks to Atom we mint one unscoped access
# token (`atom_<id_hex>_<secret_hex>`), then write it to two places:
#
#   docker/atom-bootstrap.yaml   — mounted into the Atom container; declared
#                                  under `entities: -> credentials:` so Atom
#                                  hashes the secret at first boot and stamps
#                                  the row `managed_by='config'`.
#
#   docker/.env.tokens           — loaded by docker compose; each line is
#                                  `MG_ATOM_TOKEN_<NAME>=atom_...` which the
#                                  compose file plumbs into the service's
#                                  `ATOM_SERVICE_TOKEN` env var.
#
# Both files land at the same time from the same random material, so
# `docker compose up` needs no separate init container. Rotation = rerun with
# `--force` and restart the stack.

set -euo pipefail

script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
root_dir=$(cd "${script_dir}/.." && pwd)

template_file="${root_dir}/docker/atom-bootstrap.template.yaml"
out_yaml="${root_dir}/docker/atom-bootstrap.yaml"
out_env="${root_dir}/docker/.env.tokens"

# Well-known service entity id seeded by Atom's migration 001. All Magistrala
# service tokens attach to this entity, which already carries the
# `example-service` platform role granting the actions those services need.
service_entity_id="${ATOM_SERVICE_ENTITY_ID:-00000000-0000-0000-0000-000000000003}"

# `<compose-token-env-var>:<credential-name>` pairs, one per Magistrala
# service that authenticates to Atom.
services=(
    "MG_ATOM_TOKEN_FLUXMQ_AUTH:fluxmq-auth"
    "MG_ATOM_TOKEN_FLUXMQ_NODE1:fluxmq-node1"
    "MG_ATOM_TOKEN_FLUXMQ_NODE2:fluxmq-node2"
    "MG_ATOM_TOKEN_FLUXMQ_NODE3:fluxmq-node3"
    "MG_ATOM_TOKEN_JOURNAL:journal"
    "MG_ATOM_TOKEN_NOTIFICATIONS:notifications"
    "MG_ATOM_TOKEN_RE:re"
    "MG_ATOM_TOKEN_ALARMS:alarms"
    "MG_ATOM_TOKEN_REPORTS:reports"
    "MG_ATOM_TOKEN_TIMESCALE_READER:timescale-reader"
    "MG_ATOM_TOKEN_POSTGRES_READER:postgres-reader"
)

force=0
if [[ "${1:-}" == "--force" ]]; then
    force=1
fi

if [[ ! -f "${template_file}" ]]; then
    echo "template not found: ${template_file}" >&2
    exit 1
fi

if { [[ -e "${out_yaml}" ]] || [[ -e "${out_env}" ]]; } && [[ ${force} -eq 0 ]]; then
    echo "atom secrets already exist — pass --force to regenerate:" >&2
    [[ -e "${out_yaml}" ]] && echo "  ${out_yaml}" >&2
    [[ -e "${out_env}" ]] && echo "  ${out_env}" >&2
    exit 1
fi

if ! command -v openssl >/dev/null 2>&1; then
    echo "openssl is required" >&2
    exit 1
fi

umask 077

tmp_yaml=$(mktemp "${out_yaml}.XXXXXX")
tmp_env=$(mktemp "${out_env}.XXXXXX")
trap 'rm -f "${tmp_yaml}" "${tmp_env}"' EXIT

cat "${template_file}" > "${tmp_yaml}"

cat >> "${tmp_yaml}" <<EOF

# ─── Service account credentials ─────────────────────────────────────────────
# Generated by scripts/generate-atom-secrets.sh. Each access token below is
# paired with an entry in docker/.env.tokens which docker compose maps onto
# the corresponding service's ATOM_SERVICE_TOKEN env var. Atom stamps the
# credential row managed_by='config' — invisible to introspection, not
# revocable via API. Rotate by rerunning the script with --force.
entities:
  - id: ${service_entity_id}
    kind: service
    name: magistrala-services
    credentials:
EOF

echo "# Generated by scripts/generate-atom-secrets.sh — do not commit." > "${tmp_env}"

for entry in "${services[@]}"; do
    env_key="${entry%%:*}"
    cred_name="${entry##*:}"

    id_hex=$(openssl rand -hex 16)
    secret_hex=$(openssl rand -hex 32)
    token="atom_${id_hex}_${secret_hex}"

    printf '%s=%s\n' "${env_key}" "${token}" >> "${tmp_env}"

    cat >> "${tmp_yaml}" <<EOF
      - kind: access_token
        token: ${token}
        name: ${cred_name}
EOF
done

mv "${tmp_yaml}" "${out_yaml}"
mv "${tmp_env}" "${out_env}"
trap - EXIT

chmod 0600 "${out_env}" "${out_yaml}"

cat <<EOF
generated ${#services[@]} service tokens:
  ${out_yaml}
  ${out_env}
Restart the atom container to apply the new bootstrap file.
EOF
